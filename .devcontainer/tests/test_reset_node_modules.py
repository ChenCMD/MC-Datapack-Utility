"""Check dependency regeneration against disposable volume contents."""

import importlib.util
from pathlib import Path
import tempfile
import unittest

spec = importlib.util.spec_from_file_location(
    "reset_modules", Path(__file__).resolve().parent.parent / "scripts/reset-node-modules.py")
module = importlib.util.module_from_spec(spec)
spec.loader.exec_module(module)


class ResetDependenciesTests(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory()
        self.addCleanup(self.temp.cleanup)
        self.base = Path(self.temp.name)
        self.root = self.base / "node_modules"
        self.root.mkdir()

    def test_removes_stale_modules_but_keeps_volume_cache_and_link_targets(self):
        cache = self.root / ".pnpm-store/cache"
        cache.parent.mkdir()
        cache.write_text("CACHE")
        for name in ["encoding", ".pnpm"]:
            package = self.root / name
            package.mkdir()
            (package / "index.js").write_text("STALE")
        (self.root / ".modules.yaml").write_text("OLD METADATA")
        outside = self.base / "host"
        outside.mkdir()
        sentinel = outside / "private"
        sentinel.write_text("HOST")
        (self.root / "linked").symlink_to(outside, target_is_directory=True)
        (self.root / "broken").symlink_to(self.base / "missing")
        before = self.root.stat().st_ino
        module.reset(self.root, mountinfo="")
        self.assertEqual({p.name for p in self.root.iterdir()}, {".pnpm-store"})
        self.assertEqual(self.root.stat().st_ino, before)
        self.assertEqual(cache.read_text(), "CACHE")
        self.assertEqual(sentinel.read_text(), "HOST")

    def test_rejects_symlink_roots_and_ancestors(self):
        linked = self.base / "linked"
        linked.symlink_to(self.base, target_is_directory=True)
        with self.assertRaises(ValueError):
            module.reset(linked / "node_modules", mountinfo="")
        self.root.rmdir()
        self.root.symlink_to(self.base, target_is_directory=True)
        with self.assertRaises(ValueError):
            module.reset(self.root, mountinfo="")

    def test_rejects_nested_mount_before_any_deletion(self):
        first = self.root / "first"
        first.write_text("PRESERVE")
        nested = self.root / "nested mount"
        nested.mkdir()
        mount = str(nested).replace(" ", r"\040")
        with self.assertRaises(ValueError):
            module.reset(self.root, mountinfo=f"1 0 0:1 / {mount} rw - tmpfs tmpfs rw")
        self.assertEqual(first.read_text(), "PRESERVE")


if __name__ == "__main__":
    unittest.main()
